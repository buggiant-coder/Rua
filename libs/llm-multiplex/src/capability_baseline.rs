pub struct CapabilityBaseline;

impl CapabilityBaseline {
    pub fn lookup(model_id: &str) -> Option<ModelInfo> {
        BASELINE
            .iter()
            .find(|e| e.id == model_id)
            .map(|e| e.to_model_info())
    }

    pub fn lookup_for_provider(provider_id: &str, model_id: &str) -> Option<ModelInfo> {
        BASELINE
            .iter()
            .find(|e| e.provider_id == provider_id && e.id == model_id)
            .or_else(|| BASELINE.iter().find(|e| e.id == model_id))
            .map(|e| e.to_model_info())
    }

    pub fn lookup_fuzzy(model_id: &str) -> Option<ModelInfo> {
        if let Some(info) = Self::lookup(model_id) {
            return Some(info);
        }
        if let Some(canonical_id) = canonical_alias(model_id) {
            if let Some(mut info) = Self::lookup(canonical_id) {
                info.id = model_id.to_string();
                info.probe_source = Some("baseline-alias".into());
                return Some(info);
            }
        }
        BASELINE
            .iter()
            .filter(|e| model_id.starts_with(e.id))
            .max_by_key(|e| e.id.len())
            .map(|e| {
                let mut info = e.to_model_info();
                info.id = model_id.to_string();
                info.probe_source = Some("baseline-fuzzy".into());
                info
            })
    }

    pub fn lookup_fuzzy_for_provider(provider_id: &str, model_id: &str) -> Option<ModelInfo> {
        if let Some(info) = Self::lookup_for_provider(provider_id, model_id) {
            return Some(info);
        }
        BASELINE
            .iter()
            .filter(|e| e.provider_id == provider_id && model_id.starts_with(e.id))
            .max_by_key(|e| e.id.len())
            .map(|e| {
                let mut info = e.to_model_info();
                info.id = model_id.to_string();
                info.probe_source = Some("baseline-fuzzy".into());
                info
            })
            .or_else(|| Self::lookup_fuzzy(model_id))
    }

    pub fn all_model_ids() -> Vec<&'static str> {
        BASELINE.iter().map(|e| e.id).collect()
    }
}

fn canonical_alias(model_id: &str) -> Option<&'static str> {
    match model_id.trim().to_ascii_lowercase().as_str() {
        "opus-4.8" | "opus-4-8" | "claude opus 4.8" | "claude-opus-4.8" => Some("claude-opus-4-8"),
        _ => None,
    }
}
